--------------------------------------------------------------------------------
-- Uebersicht: Szenen mit belegtem Speicher
--------------------------------------------------------------------------------
CREATE OR REPLACE VIEW FGS_SCENE_INFO AS
SELECT s.ID,
       s.NAME,
       s.SOURCE_KIND,
       s.SPLAT_COUNT,
       s.EXAGGERATION,
       ROUND(NVL(b.BYTES, 0) / 1048576, 2) AS MB,
       s.CREATED
  FROM FGS_SCENE s
  LEFT JOIN (SELECT SCENE_ID, SUM(DBMS_LOB.GETLENGTH(DATA)) AS BYTES
               FROM FGS_BLOCK
              GROUP BY SCENE_ID) b
    ON b.SCENE_ID = s.ID;

